#!/usr/bin/env python3
"""Course prices and payment links, in one place. Writes site/assets/pricing.js.

Business rule (owner, 2026-11-09): low pay-as-you-go prices, with a flat 20% admin charge shown on top
(taxes and upkeep). Free entry stays free: Part/Module 1 of every course is a free preview, and some
courses (EMBA subjects 01-03, Chapter-labelled pages) are fully free.

To go live, the owner only fills PAY_LINKS below with the hosted payment links made in the payment
provider (for example a Razorpay Payment Page for UPI/cards in India, or a Stripe Payment Link for cards
elsewhere), one per tier. While a tier has no link, pay.html stays in test mode for that tier.
No keys, secrets or bank numbers ever go in this file: a payment link is a public URL.
"""
import json, pathlib

S = pathlib.Path(__file__).resolve().parent.parent / 'site'
ADMIN = 0.20

# (tier id, label, file pattern matched against the course key, base price INR, base price USD)
# First match wins. The course key is the course page file, or the series hub for one-lesson-per-page series.
TIERS = [
    ('emba',      'Executive MBA subject',       r'^emba-\d\d\.html$',               799, 12),
    ('executive', 'Executive programme module',  r'^executive-module-',              799, 12),
    ('series',    'Lesson series',               r'^(career-launch|electrical-academy|ai-side-income)\.html$', 399, 6),
    ('cpd',       'CPD course',                  r'^cpd-',                           299, 5),
    ('school',    'School course',               r'^school-',                        99,  2),
    ('course',    'Course',                      r'.',                               199, 3),
]

# Hosted payment links per tier, filled by the owner when the provider account is ready. Example:
#   'course': {'INR': 'https://rzp.io/l/xxxx', 'USD': 'https://buy.stripe.com/xxxx'}
PAY_LINKS = {}


def total(base):
    return round(base * (1 + ADMIN), 2)


def main():
    rows = []
    for tid, label, pat, inr, usd in TIERS:
        rows.append({'id': tid, 'label': label, 'pattern': pat,
                     'INR': {'base': inr, 'admin': round(inr * ADMIN, 2), 'total': total(inr)},
                     'USD': {'base': usd, 'admin': round(usd * ADMIN, 2), 'total': total(usd)},
                     'links': PAY_LINKS.get(tid, {})})
    js = ('/* Generated by tools/build_pricing.py. Do not edit here. */\n'
          '(function(){var T=' + json.dumps(rows, separators=(',', ':')) + ';\n'
          'function tier(key){for(var i=0;i<T.length;i++){if(new RegExp(T[i].pattern).test(key||""))return T[i]}return null}\n'
          'function cur(){try{var l=(navigator.language||"")+" "+(Intl.DateTimeFormat().resolvedOptions().timeZone||"");return /IN|Kolkata|Calcutta/.test(l)?"INR":"USD"}catch(e){return "USD"}}\n'
          'function fmt(c,n){return (c==="INR"?"\\u20b9":"$")+(n%1?n.toFixed(2):n)}\n'
          'window.HFLPrice={tiers:T,tier:tier,currency:cur,fmt:fmt,admin:' + str(ADMIN) + '};})();\n')
    (S / 'assets' / 'pricing.js').write_text(js)
    print('pricing written: %d tiers, %d with live links' % (len(rows), sum(1 for r in rows if r['links'])))


if __name__ == '__main__':
    main()
